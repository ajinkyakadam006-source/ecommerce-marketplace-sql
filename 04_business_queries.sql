-- TOPIC 1: BASIC FILTERING, SORTING AND AGGREGATES
-- Queries 1-12

-- Q01. Display all customers from Mumbai.
SELECT *
FROM CUSTOMERS
WHERE CITY = 'Mumbai';

-- Q02. Display products priced above Rs. 1000.
SELECT PRODUCT_ID, PRODUCT_NAME, PRICE
FROM PRODUCTS
WHERE PRICE > 1000
ORDER BY PRICE DESC;

-- Q03. Display products with prices between Rs. 500 and Rs. 2500.
SELECT PRODUCT_NAME, PRICE
FROM PRODUCTS
WHERE PRICE BETWEEN 500 AND 2500
ORDER BY PRICE;

-- Q04. Display products whose stock is below 30.
SELECT PRODUCT_NAME, STOCK_QUANTITY
FROM PRODUCTS
WHERE STOCK_QUANTITY < 30
ORDER BY STOCK_QUANTITY;

-- Q05. Find customers whose names start with 'A'.
SELECT CUSTOMER_ID, CUSTOMER_NAME
FROM CUSTOMERS
WHERE CUSTOMER_NAME LIKE 'A%';

-- Q06. Display all distinct customer cities.
SELECT DISTINCT CITY
FROM CUSTOMERS
ORDER BY CITY;

-- Q07. Count the total number of customers.
SELECT COUNT(*) AS TOTAL_CUSTOMERS
FROM CUSTOMERS;

-- Q08. Find the average, minimum and maximum product price.
SELECT AVG(PRICE) AS AVG_PRICE,
       MIN(PRICE) AS MIN_PRICE,
       MAX(PRICE) AS MAX_PRICE
FROM PRODUCTS;

-- Q09. Calculate the total value of current product inventory.
SELECT SUM(PRICE * STOCK_QUANTITY) AS INVENTORY_VALUE
FROM PRODUCTS;

-- Q10. Display orders placed during January 2026.
SELECT ORDER_ID, CUSTOMER_ID, ORDER_DATE, ORDER_STATUS
FROM ORDERS
WHERE ORDER_DATE >= DATE '2026-01-01'
  AND ORDER_DATE < DATE '2026-02-01'
ORDER BY ORDER_DATE;

-- Q11. Display orders that are delivered or shipped.
SELECT ORDER_ID, ORDER_DATE, ORDER_STATUS
FROM ORDERS
WHERE ORDER_STATUS IN ('DELIVERED', 'SHIPPED')
ORDER BY ORDER_DATE DESC;

-- Q12. Count successful payments and calculate their total amount.
SELECT COUNT(*) AS SUCCESSFUL_PAYMENTS,
       SUM(PAYMENT_AMOUNT) AS TOTAL_SUCCESSFUL_AMOUNT
FROM PAYMENTS
WHERE PAYMENT_STATUS = 'SUCCESS';


-- TOPIC 2: JOINS
-- Queries 13-28

-- Q13. Display each order with the customer's name.
SELECT O.ORDER_ID, C.CUSTOMER_NAME,
       O.ORDER_DATE, O.ORDER_STATUS
FROM ORDERS O
INNER JOIN CUSTOMERS C
ON O.CUSTOMER_ID = C.CUSTOMER_ID
ORDER BY O.ORDER_ID;

-- Q14. Display each product with its category name.
SELECT P.PRODUCT_ID, P.PRODUCT_NAME,
       C.CATEGORY_NAME, P.PRICE
FROM PRODUCTS P
INNER JOIN CATEGORIES C
ON P.CATEGORY_ID = C.CATEGORY_ID
ORDER BY C.CATEGORY_NAME, P.PRODUCT_NAME;

-- Q15. Display order items with product names and quantities.
SELECT OI.ORDER_ID, P.PRODUCT_NAME,
       OI.QUANTITY, OI.UNIT_PRICE
FROM ORDER_ITEMS OI
INNER JOIN PRODUCTS P
ON OI.PRODUCT_ID = P.PRODUCT_ID
ORDER BY OI.ORDER_ID;

-- Q16. Display customers and their orders, including customers
-- who have not placed any orders.
SELECT C.CUSTOMER_ID, C.CUSTOMER_NAME, O.ORDER_ID
FROM CUSTOMERS C
LEFT JOIN ORDERS O
ON C.CUSTOMER_ID = O.CUSTOMER_ID
ORDER BY C.CUSTOMER_ID;

-- Q17. Display each order with its payment details.
SELECT O.ORDER_ID, O.ORDER_STATUS,
       P.PAYMENT_METHOD, P.PAYMENT_AMOUNT, P.PAYMENT_STATUS
FROM ORDERS O
INNER JOIN PAYMENTS P
ON O.ORDER_ID = P.ORDER_ID
ORDER BY O.ORDER_ID;

-- Q18. Display the customer, order and payment status together.
SELECT C.CUSTOMER_NAME, O.ORDER_ID,
       O.ORDER_STATUS, P.PAYMENT_STATUS
FROM CUSTOMERS C
INNER JOIN ORDERS O
ON C.CUSTOMER_ID = O.CUSTOMER_ID
INNER JOIN PAYMENTS P
ON O.ORDER_ID = P.ORDER_ID
ORDER BY C.CUSTOMER_NAME;

-- Q19. Calculate the item subtotal for every order.
SELECT ORDER_ID,
       SUM(QUANTITY * UNIT_PRICE) AS ORDER_SUBTOTAL
FROM ORDER_ITEMS
GROUP BY ORDER_ID
ORDER BY ORDER_ID;

-- Q20. Display each order with customer name and order subtotal.
SELECT C.CUSTOMER_NAME, O.ORDER_ID,
       SUM(OI.QUANTITY * OI.UNIT_PRICE) AS ORDER_SUBTOTAL
FROM CUSTOMERS C
INNER JOIN ORDERS O
ON C.CUSTOMER_ID = O.CUSTOMER_ID
INNER JOIN ORDER_ITEMS OI
ON O.ORDER_ID = OI.ORDER_ID
GROUP BY C.CUSTOMER_NAME, O.ORDER_ID
ORDER BY O.ORDER_ID;

-- Q21. Display products that have appeared in order items.
SELECT DISTINCT P.PRODUCT_ID, P.PRODUCT_NAME, P.PRICE
FROM PRODUCTS P
INNER JOIN ORDER_ITEMS OI
ON P.PRODUCT_ID = OI.PRODUCT_ID
ORDER BY P.PRODUCT_NAME;

-- Q22. Display each category and its products.
SELECT C.CATEGORY_NAME, P.PRODUCT_NAME, P.PRICE
FROM CATEGORIES C
INNER JOIN PRODUCTS P
ON C.CATEGORY_ID = P.CATEGORY_ID
ORDER BY C.CATEGORY_NAME, P.PRODUCT_NAME;

-- Q23. Display all products, including products never ordered.
SELECT P.PRODUCT_ID, P.PRODUCT_NAME, OI.ORDER_ID
FROM PRODUCTS P
LEFT JOIN ORDER_ITEMS OI
ON P.PRODUCT_ID = OI.PRODUCT_ID
ORDER BY P.PRODUCT_ID;

-- Q24. Display orders with the products purchased in each order.
SELECT O.ORDER_ID, P.PRODUCT_NAME,
       OI.QUANTITY, OI.UNIT_PRICE
FROM ORDERS O
INNER JOIN ORDER_ITEMS OI
ON O.ORDER_ID = OI.ORDER_ID
INNER JOIN PRODUCTS P
ON OI.PRODUCT_ID = P.PRODUCT_ID
ORDER BY O.ORDER_ID, P.PRODUCT_NAME;

-- Q25. Calculate the total quantity sold for each product.
SELECT P.PRODUCT_NAME,
       SUM(OI.QUANTITY) AS TOTAL_QUANTITY_SOLD
FROM PRODUCTS P
INNER JOIN ORDER_ITEMS OI
ON P.PRODUCT_ID = OI.PRODUCT_ID
INNER JOIN ORDERS O
ON OI.ORDER_ID = O.ORDER_ID
WHERE O.ORDER_STATUS <> 'CANCELLED'
GROUP BY P.PRODUCT_NAME
ORDER BY TOTAL_QUANTITY_SOLD DESC;

-- Q26. Display customers who have made successful payments.
SELECT DISTINCT C.CUSTOMER_ID, C.CUSTOMER_NAME
FROM CUSTOMERS C
INNER JOIN ORDERS O
ON C.CUSTOMER_ID = O.CUSTOMER_ID
INNER JOIN PAYMENTS P
ON O.ORDER_ID = P.ORDER_ID
WHERE P.PAYMENT_STATUS = 'SUCCESS'
ORDER BY C.CUSTOMER_NAME;

-- Q27. Calculate order-item revenue by product category.
SELECT C.CATEGORY_NAME,
       SUM(OI.QUANTITY * OI.UNIT_PRICE) AS CATEGORY_REVENUE
FROM CATEGORIES C
INNER JOIN PRODUCTS P
ON C.CATEGORY_ID = P.CATEGORY_ID
INNER JOIN ORDER_ITEMS OI
ON P.PRODUCT_ID = OI.PRODUCT_ID
INNER JOIN ORDERS O
ON OI.ORDER_ID = O.ORDER_ID
WHERE O.ORDER_STATUS <> 'CANCELLED'
GROUP BY C.CATEGORY_NAME
ORDER BY CATEGORY_REVENUE DESC;

-- Q28. Display customer names, product names and quantities
-- for all products ordered by each customer.
SELECT C.CUSTOMER_NAME, P.PRODUCT_NAME, OI.QUANTITY
FROM CUSTOMERS C
INNER JOIN ORDERS O
ON C.CUSTOMER_ID = O.CUSTOMER_ID
INNER JOIN ORDER_ITEMS OI
ON O.ORDER_ID = OI.ORDER_ID
INNER JOIN PRODUCTS P
ON OI.PRODUCT_ID = P.PRODUCT_ID
ORDER BY C.CUSTOMER_NAME, P.PRODUCT_NAME;


-- TOPIC 3: SUBQUERIES
-- Queries 29-38

-- Q29. Find products priced above the average product price.
SELECT PRODUCT_NAME, PRICE
FROM PRODUCTS
WHERE PRICE > (SELECT AVG(PRICE) FROM PRODUCTS)
ORDER BY PRICE DESC;

-- Q30. Find products priced at the maximum product price.
SELECT PRODUCT_NAME, PRICE
FROM PRODUCTS
WHERE PRICE = (SELECT MAX(PRICE) FROM PRODUCTS);

-- Q31. Find customers who have placed at least one order.
SELECT CUSTOMER_ID, CUSTOMER_NAME
FROM CUSTOMERS C
WHERE EXISTS (
    SELECT 1
    FROM ORDERS O
    WHERE O.CUSTOMER_ID = C.CUSTOMER_ID
);

-- Q32. Find customers who have never placed an order.
SELECT CUSTOMER_ID, CUSTOMER_NAME
FROM CUSTOMERS C
WHERE NOT EXISTS (
    SELECT 1
    FROM ORDERS O
    WHERE O.CUSTOMER_ID = C.CUSTOMER_ID
);

-- Q33. Find products that have never been ordered.
SELECT PRODUCT_ID, PRODUCT_NAME
FROM PRODUCTS P
WHERE NOT EXISTS (
    SELECT 1
    FROM ORDER_ITEMS OI
    WHERE OI.PRODUCT_ID = P.PRODUCT_ID
);

-- Q34. Find orders whose item subtotal is greater than
-- the average order subtotal.
SELECT ORDER_ID
FROM ORDER_ITEMS
GROUP BY ORDER_ID
HAVING SUM(QUANTITY * UNIT_PRICE) >
       (SELECT AVG(ORDER_SUBTOTAL)
        FROM (
            SELECT SUM(QUANTITY * UNIT_PRICE) AS ORDER_SUBTOTAL
            FROM ORDER_ITEMS
            GROUP BY ORDER_ID
        ));

-- Q35. Find customers who have placed more orders than
-- the average number of orders per customer.
SELECT C.CUSTOMER_ID, C.CUSTOMER_NAME
FROM CUSTOMERS C
WHERE (
    SELECT COUNT(*)
    FROM ORDERS O
    WHERE O.CUSTOMER_ID = C.CUSTOMER_ID
) > (
    SELECT AVG(ORDER_COUNT)
    FROM (
        SELECT COUNT(*) AS ORDER_COUNT
        FROM CUSTOMERS C2
        LEFT JOIN ORDERS O2
        ON C2.CUSTOMER_ID = O2.CUSTOMER_ID
        GROUP BY C2.CUSTOMER_ID
    )
);

-- Q36. Find products that belong to categories containing
-- at least one product priced above Rs. 2000.
SELECT PRODUCT_NAME, CATEGORY_ID, PRICE
FROM PRODUCTS P
WHERE CATEGORY_ID IN (
    SELECT CATEGORY_ID
    FROM PRODUCTS
    WHERE PRICE > 2000
)
ORDER BY CATEGORY_ID, PRODUCT_NAME;

-- Q37. Find orders whose payment amount is greater than
-- the average payment amount.
SELECT ORDER_ID, PAYMENT_AMOUNT
FROM PAYMENTS
WHERE PAYMENT_AMOUNT > (
    SELECT AVG(PAYMENT_AMOUNT)
    FROM PAYMENTS
)
ORDER BY PAYMENT_AMOUNT DESC;

-- Q38. Find categories whose average product price exceeds
-- the overall average product price.
SELECT C.CATEGORY_NAME, AVG(P.PRICE) AS AVG_CATEGORY_PRICE
FROM CATEGORIES C
INNER JOIN PRODUCTS P
ON C.CATEGORY_ID = P.CATEGORY_ID
GROUP BY C.CATEGORY_ID, C.CATEGORY_NAME
HAVING AVG(P.PRICE) > (
    SELECT AVG(PRICE)
    FROM PRODUCTS
);


-- TOPIC 4: GROUP BY AND HAVING
-- Queries 39-50

-- Q39. Count orders by order status.
SELECT ORDER_STATUS, COUNT(*) AS TOTAL_ORDERS
FROM ORDERS
GROUP BY ORDER_STATUS
ORDER BY TOTAL_ORDERS DESC;

-- Q40. Count customers in each city.
SELECT CITY, COUNT(*) AS TOTAL_CUSTOMERS
FROM CUSTOMERS
GROUP BY CITY
ORDER BY TOTAL_CUSTOMERS DESC, CITY;

-- Q41. Calculate the average product price by category.
SELECT C.CATEGORY_NAME, AVG(P.PRICE) AS AVG_PRICE
FROM CATEGORIES C
INNER JOIN PRODUCTS P
ON C.CATEGORY_ID = P.CATEGORY_ID
GROUP BY C.CATEGORY_ID, C.CATEGORY_NAME
ORDER BY AVG_PRICE DESC;

-- Q42. Count orders placed by each customer.
SELECT C.CUSTOMER_ID, C.CUSTOMER_NAME,
       COUNT(O.ORDER_ID) AS TOTAL_ORDERS
FROM CUSTOMERS C
LEFT JOIN ORDERS O
ON C.CUSTOMER_ID = O.CUSTOMER_ID
GROUP BY C.CUSTOMER_ID, C.CUSTOMER_NAME
ORDER BY TOTAL_ORDERS DESC;

-- Q43. Display customers who have placed at least two orders.
SELECT C.CUSTOMER_ID, C.CUSTOMER_NAME,
       COUNT(O.ORDER_ID) AS TOTAL_ORDERS
FROM CUSTOMERS C
INNER JOIN ORDERS O
ON C.CUSTOMER_ID = O.CUSTOMER_ID
GROUP BY C.CUSTOMER_ID, C.CUSTOMER_NAME
HAVING COUNT(O.ORDER_ID) >= 2
ORDER BY TOTAL_ORDERS DESC;

-- Q44. Display categories containing more than two products.
SELECT C.CATEGORY_NAME, COUNT(P.PRODUCT_ID) AS TOTAL_PRODUCTS
FROM CATEGORIES C
INNER JOIN PRODUCTS P
ON C.CATEGORY_ID = P.CATEGORY_ID
GROUP BY C.CATEGORY_ID, C.CATEGORY_NAME
HAVING COUNT(P.PRODUCT_ID) > 2;

-- Q45. Display products whose total ordered quantity exceeds one.
SELECT P.PRODUCT_NAME, SUM(OI.QUANTITY) AS TOTAL_QUANTITY
FROM PRODUCTS P
INNER JOIN ORDER_ITEMS OI
ON P.PRODUCT_ID = OI.PRODUCT_ID
GROUP BY P.PRODUCT_ID, P.PRODUCT_NAME
HAVING SUM(OI.QUANTITY) > 1
ORDER BY TOTAL_QUANTITY DESC;

-- Q46. Display payment methods with at least two payments.
SELECT PAYMENT_METHOD, COUNT(*) AS TOTAL_PAYMENTS
FROM PAYMENTS
GROUP BY PAYMENT_METHOD
HAVING COUNT(*) >= 2
ORDER BY TOTAL_PAYMENTS DESC;

-- Q47. Calculate total successful payment amount by method.
SELECT PAYMENT_METHOD,
       SUM(PAYMENT_AMOUNT) AS TOTAL_AMOUNT
FROM PAYMENTS
WHERE PAYMENT_STATUS = 'SUCCESS'
GROUP BY PAYMENT_METHOD
ORDER BY TOTAL_AMOUNT DESC;

-- Q48. Display customers whose non-cancelled order subtotals
-- exceed Rs. 3000 in total.
SELECT C.CUSTOMER_ID, C.CUSTOMER_NAME,
       SUM(OI.QUANTITY * OI.UNIT_PRICE) AS TOTAL_ORDER_VALUE
FROM CUSTOMERS C
INNER JOIN ORDERS O
ON C.CUSTOMER_ID = O.CUSTOMER_ID
INNER JOIN ORDER_ITEMS OI
ON O.ORDER_ID = OI.ORDER_ID
WHERE O.ORDER_STATUS <> 'CANCELLED'
GROUP BY C.CUSTOMER_ID, C.CUSTOMER_NAME
HAVING SUM(OI.QUANTITY * OI.UNIT_PRICE) > 3000
ORDER BY TOTAL_ORDER_VALUE DESC;

-- Q49. Display categories with total order-item revenue
-- above Rs. 3000, excluding cancelled orders.
SELECT C.CATEGORY_NAME,
       SUM(OI.QUANTITY * OI.UNIT_PRICE) AS TOTAL_REVENUE
FROM CATEGORIES C
INNER JOIN PRODUCTS P
ON C.CATEGORY_ID = P.CATEGORY_ID
INNER JOIN ORDER_ITEMS OI
ON P.PRODUCT_ID = OI.PRODUCT_ID
INNER JOIN ORDERS O
ON OI.ORDER_ID = O.ORDER_ID
WHERE O.ORDER_STATUS <> 'CANCELLED'
GROUP BY C.CATEGORY_ID, C.CATEGORY_NAME
HAVING SUM(OI.QUANTITY * OI.UNIT_PRICE) > 3000
ORDER BY TOTAL_REVENUE DESC;

-- Q50. Display order status with an average item subtotal
-- greater than Rs. 2000.
SELECT O.ORDER_STATUS,
       AVG(ORDER_TOTAL) AS AVG_ORDER_SUBTOTAL
FROM ORDERS O
INNER JOIN (
    SELECT ORDER_ID,
           SUM(QUANTITY * UNIT_PRICE) AS ORDER_TOTAL
    FROM ORDER_ITEMS
    GROUP BY ORDER_ID
) OT
ON O.ORDER_ID = OT.ORDER_ID
GROUP BY O.ORDER_STATUS
HAVING AVG(ORDER_TOTAL) > 2000
ORDER BY AVG_ORDER_SUBTOTAL DESC;
