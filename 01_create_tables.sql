-- File: 01_create_tables.sql

CREATE TABLE CUSTOMERS (
    CUSTOMER_ID NUMBER(6) PRIMARY KEY,
    CUSTOMER_NAME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(100) UNIQUE NOT NULL,
    PHONE VARCHAR2(15),
    CITY VARCHAR2(50),
    CREATED_AT DATE DEFAULT SYSDATE
);

CREATE TABLE CATEGORIES (
    CATEGORY_ID NUMBER(4) PRIMARY KEY,
    CATEGORY_NAME VARCHAR2(50) UNIQUE NOT NULL
);

CREATE TABLE PRODUCTS (
    PRODUCT_ID NUMBER(6) PRIMARY KEY,
    PRODUCT_NAME VARCHAR2(100) NOT NULL,
    CATEGORY_ID NUMBER(4) NOT NULL,
    PRICE NUMBER(10,2) CHECK (PRICE >= 0),
    STOCK_QUANTITY NUMBER(6) DEFAULT 0
        CHECK (STOCK_QUANTITY >= 0),
    FOREIGN KEY (CATEGORY_ID)
        REFERENCES CATEGORIES(CATEGORY_ID)
);

CREATE TABLE ORDERS (
    ORDER_ID NUMBER(6) PRIMARY KEY,
    CUSTOMER_ID NUMBER(6) NOT NULL,
    ORDER_DATE DATE DEFAULT SYSDATE,
    ORDER_STATUS VARCHAR2(20) DEFAULT 'PLACED'
        CHECK (ORDER_STATUS IN
        ('PLACED','SHIPPED','DELIVERED','CANCELLED')),
    FOREIGN KEY (CUSTOMER_ID)
        REFERENCES CUSTOMERS(CUSTOMER_ID)
);

CREATE TABLE ORDER_ITEMS (
    ORDER_ITEM_ID NUMBER(8) PRIMARY KEY,
    ORDER_ID NUMBER(6) NOT NULL,
    PRODUCT_ID NUMBER(6) NOT NULL,
    QUANTITY NUMBER(5) CHECK (QUANTITY > 0),
    UNIT_PRICE NUMBER(10,2) CHECK (UNIT_PRICE >= 0),
    FOREIGN KEY (ORDER_ID) REFERENCES ORDERS(ORDER_ID),
    FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID)
);

CREATE TABLE PAYMENTS (
    PAYMENT_ID NUMBER(6) PRIMARY KEY,
    ORDER_ID NUMBER(6) UNIQUE NOT NULL,
    PAYMENT_DATE DATE DEFAULT SYSDATE,
    PAYMENT_METHOD VARCHAR2(20)
        CHECK (PAYMENT_METHOD IN
        ('UPI','CARD','COD','NET_BANKING')),
    PAYMENT_AMOUNT NUMBER(10,2) CHECK (PAYMENT_AMOUNT >= 0),
    PAYMENT_STATUS VARCHAR2(20) DEFAULT 'PENDING'
        CHECK (PAYMENT_STATUS IN
        ('PENDING','SUCCESS','FAILED','REFUNDED')),
    FOREIGN KEY (ORDER_ID) REFERENCES ORDERS(ORDER_ID)
);